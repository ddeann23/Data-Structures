
public class Node {
	//Attributes
	private Node next;
	private int data;
	
	//Constructors
	
	
	
	//Getter and Setters
	public int getData() {
		return data;
	}
	
	public Node getNext() {
		return next;
	}
	
	public void setData(int data) {
		this.data = data;
	}
	
	public void setNext(Node next) {
		this.next = next;
	}
	
}
